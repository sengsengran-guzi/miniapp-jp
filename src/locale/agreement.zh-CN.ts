/** 协议单段：小标题 + 若干自然段。 */
export interface AgreementSection {
  /** 段落小标题（如「一、我们如何收集信息」）；空串表示无标题的引言段 */
  heading: string
  /** 正文自然段（每个元素渲染为一段） */
  body: string[]
}

/** 一篇协议文档。 */
export interface AgreementDoc {
  /** 文档标题 */
  title: string
  /** 生效/更新日期 */
  updated: string
  /** 适用主体说明（页眉一行） */
  publisher: string
  /** 正文段落 */
  sections: AgreementSection[]
}

